namespace ASToolkit.Core.Rooms;

/// <summary>
/// Specifies the kind of furniture a piece is, for grouping pieces into parts of a room.
/// </summary>
public enum PieceFamily
{
    /// <summary>
    /// A table.
    /// </summary>
    Table,

    /// <summary>
    /// A chair.
    /// </summary>
    Chair,

    /// <summary>
    /// A computer or a monitor, on a table or on a wall.
    /// </summary>
    Computer,

    /// <summary>
    /// A filing cabinet.
    /// </summary>
    Cabinet,

    /// <summary>
    /// A rack of shelves.
    /// </summary>
    Shelf,

    /// <summary>
    /// A small crate.
    /// </summary>
    Crate,

    /// <summary>
    /// A pile of boxes.
    /// </summary>
    Boxes,

    /// <summary>
    /// A barrel, plain or radioactive.
    /// </summary>
    Barrel,

    /// <summary>
    /// A gas cylinder.
    /// </summary>
    Cylinder,

    /// <summary>
    /// A shipping container.
    /// </summary>
    Container,

    /// <summary>
    /// A forklift.
    /// </summary>
    Truck,

    /// <summary>
    /// A missile.
    /// </summary>
    Missile,

    /// <summary>
    /// Test tubes, flasks and lab equipment.
    /// </summary>
    Labware,

    /// <summary>
    /// A big wall computer.
    /// </summary>
    Console,

    /// <summary>
    /// A free-standing server bank (443).
    /// </summary>
    Bank,

    /// <summary>
    /// A transformer or an electric panel.
    /// </summary>
    Machine,

    /// <summary>
    /// A potted plant.
    /// </summary>
    Plant,

    /// <summary>
    /// A water cooler.
    /// </summary>
    Water,

    /// <summary>
    /// Books, gym gear, toilets, televisions and other furniture of living quarters.
    /// </summary>
    Household
}
